import Foundation

struct ContentItem: Identifiable, Codable {
    let id: UUID
    let teamId: String
    let type: ContentType
    let headline: String
    let body: String
    let kickoffTime: Date?
    let emotionalContext: String?
    let publishedAt: Date

    // Raw talking points — decoded differently based on type
    private let talkingPointsRaw: TalkingPointsPayload

    // Everyone's talking about — cross-team feed
    let everyoneTalking: Bool
    let everyoneTalkingHeadline: String?
    let everyoneTalkingBody: String?
    let everyoneTalkingTalkingPoints: [String]?
    let worthKnowing: Bool

    // Immersive card fields
    let immersiveHeadline: String?
    let immersiveContext: String?
    let immersiveContextFallback: String?

    // Analogy review state
    let analogyReviewed: Bool
    let analogyApproved: Bool
    let analogyAutoPublished: Bool

    /// Teams referenced in the headline or body. Drives the team-crest
    /// header on ContentDetailView — 1 crest for 1 entry, 2 crests for
    /// 2 entries, no crests for 3+ entries OR nil (legacy rows). Optional
    /// so older items decoded from cache don't break. V2.0.
    let affectedTeamIds: [String]?

    /// Goal scorers + minutes for a post-game result article (075). Reuses the
    /// live-box Scorer shape. Nil for non-result items / legacy rows.
    let scorers: [LiveMatchBrief.Scorer]?

    /// Links this content_item to a specific upcoming fixture. When set,
    /// the iOS Calendar tab uses this to navigate from a fixture row to
    /// the preview's ContentDetailView. Format:
    /// `"<team_id>:<iso-date>:<opponent-slug>"`. Used by the V2.0 WC
    /// pre-tournament preview content. nil for normal feed items.
    /// See Lesson 78.
    let previewFixtureId: String?

    /// For a pre-match preview (`previewFixtureId != nil`), the one-line
    /// favourite verdict shown as a sub-header in the detail view, e.g.
    /// "Spain are the clear favourites" (mapped deterministically from FIFA
    /// ranks by the gd-wc-preview routine). For a result item it carries the
    /// scoreline. nil for ordinary news.
    let matchResult: String?
    /// API-Football league id of the competition this card is about (migration
    /// 094). Nil on rows written before 2026-09-08 and on cards that are not
    /// about one match; the badge then falls back to the card type alone.
    let leagueId: Int?

    /// The competition, when the card records one.
    var competition: Competition? { leagueId.flatMap(Competition.init(rawValue:)) }

    /// Badge label for a cup card: "LEAGUE CUP" says more than "MATCH DAY" on a
    /// Tuesday in September, which is the whole reason the column exists. Nil
    /// for the Premier League and the World Championship, where the card type
    /// is the more useful of the two, and for rows with no competition.
    var cupBadgeLabel: String? {
        guard let competition, competition.isCup else { return nil }
        return competition.badge
    }

    /// What she needs to KNOW, as opposed to `talkingPoints` (what she can
    /// SAY). Up to three levelled cards; levels 1-2 render above Things to
    /// say, level 3 ("To impress") sits behind a +. Migration 090. Nil on
    /// every row written before 2026-09-07 and on Edge-template rows — the
    /// section hides.
    let infoCards: [InfoCard]?

    enum ContentType: String, Codable {
        case news
        case matchday
        /// Weekly forward-look generated by gd-sunday-brief routine.
        /// T2+ gated client-side and server-side. V1.1 task C2.
        case sundayBrief = "sunday_brief"
        /// Pre-match starting XI brief — fires ~60min before kickoff.
        /// Generated by gd-starting-xi cloud routine, fired by
        /// match-watcher's STARTING_XI trigger. Same render path as
        /// news/matchday (push + feed card), no tier gating beyond T1+.
        /// V2.0.
        case startingXi = "starting_xi"
    }

    enum CodingKeys: String, CodingKey {
        case id
        case teamId = "team_id"
        case type
        case headline
        case body
        case talkingPointsRaw = "talking_points"
        case kickoffTime = "kickoff_time"
        case emotionalContext = "emotional_context"
        case publishedAt = "published_at"

        // Everyone's talking about
        case everyoneTalking = "everyone_talking"
        case everyoneTalkingHeadline = "everyone_talking_headline"
        case everyoneTalkingBody = "everyone_talking_body"
        case everyoneTalkingTalkingPoints = "everyone_talking_talking_points"
        case worthKnowing = "worth_knowing"

        // Immersive card
        case immersiveHeadline = "immersive_headline"
        case immersiveContext = "immersive_context"
        case immersiveContextFallback = "immersive_context_fallback"

        // Analogy review
        case analogyReviewed = "analogy_reviewed"
        case analogyApproved = "analogy_approved"
        case analogyAutoPublished = "analogy_auto_published"

        // V2.0 team-crest header
        case affectedTeamIds = "affected_team_ids"
        case scorers = "goal_events"

        // V2.0 WC pre-tournament preview linking — see previewFixtureId
        case previewFixtureId = "preview_fixture_id"
        case matchResult = "match_result"
        case leagueId = "league_id"
        case infoCards = "info_cards"
    }

    // Custom decoder for backward compatibility with cached items missing new fields
    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)

        id = try container.decode(UUID.self, forKey: .id)
        teamId = try container.decode(String.self, forKey: .teamId)
        type = try container.decode(ContentType.self, forKey: .type)
        headline = try container.decode(String.self, forKey: .headline)
        body = try container.decode(String.self, forKey: .body)
        talkingPointsRaw = try container.decode(TalkingPointsPayload.self, forKey: .talkingPointsRaw)
        kickoffTime = try container.decodeIfPresent(Date.self, forKey: .kickoffTime)
        emotionalContext = try container.decodeIfPresent(String.self, forKey: .emotionalContext)
        publishedAt = try container.decode(Date.self, forKey: .publishedAt)

        // New fields — all default to false/nil for backward compatibility
        everyoneTalking = (try? container.decodeIfPresent(Bool.self, forKey: .everyoneTalking)) ?? false
        everyoneTalkingHeadline = try? container.decodeIfPresent(String.self, forKey: .everyoneTalkingHeadline)
        everyoneTalkingBody = try? container.decodeIfPresent(String.self, forKey: .everyoneTalkingBody)
        everyoneTalkingTalkingPoints = try? container.decodeIfPresent([String].self, forKey: .everyoneTalkingTalkingPoints)
        worthKnowing = (try? container.decodeIfPresent(Bool.self, forKey: .worthKnowing)) ?? false
        immersiveHeadline = try? container.decodeIfPresent(String.self, forKey: .immersiveHeadline)
        immersiveContext = try? container.decodeIfPresent(String.self, forKey: .immersiveContext)
        immersiveContextFallback = try? container.decodeIfPresent(String.self, forKey: .immersiveContextFallback)
        analogyReviewed = (try? container.decodeIfPresent(Bool.self, forKey: .analogyReviewed)) ?? false
        analogyApproved = (try? container.decodeIfPresent(Bool.self, forKey: .analogyApproved)) ?? false
        analogyAutoPublished = (try? container.decodeIfPresent(Bool.self, forKey: .analogyAutoPublished)) ?? false
        affectedTeamIds = try? container.decodeIfPresent([String].self, forKey: .affectedTeamIds)
        scorers = try? container.decodeIfPresent([LiveMatchBrief.Scorer].self, forKey: .scorers)
        previewFixtureId = try? container.decodeIfPresent(String.self, forKey: .previewFixtureId)
        matchResult = try? container.decodeIfPresent(String.self, forKey: .matchResult)
        leagueId = try? container.decodeIfPresent(Int.self, forKey: .leagueId)
        // Lenient: one malformed card must not take the item down. Decode the
        // array element by element and keep what parses.
        infoCards = (try? container.decodeIfPresent([LossyInfoCard].self, forKey: .infoCards))?
            .compactMap(\.card)
            .sorted { $0.level < $1.level }
    }

    /// The context/analogy line to display on the immersive card.
    /// The AI critic screens analogies before they reach the DB — if `immersive_context`
    /// is non-null, it has passed the critic (possibly after a rewrite). Show that.
    /// Only fall back to the factual line if no analogy survived review.
    var displayContext: String? {
        if let context = immersiveContext, !context.isEmpty {
            return context
        }
        return immersiveContextFallback
    }

    var regularTalkingPoints: [String] {
        switch talkingPointsRaw {
        case .simple(let points):
            return points
        case .matchday(let data):
            return data.regular
        }
    }

    var postMatchCheatSheet: PostMatchCheatSheet? {
        guard case .matchday(let data) = talkingPointsRaw else { return nil }
        return data.postMatch
    }

    var matchdayMetadata: MatchdayMetadata? {
        guard case .matchday(let data) = talkingPointsRaw else { return nil }
        return data.metadata
    }
}

// MARK: - Info cards (what she needs to know)

/// One levelled fact card. `level` 1 = the gist, 2 = the wider picture,
/// 3 = to impress. Neutral text — the sister voice lives in talking points.
struct InfoCard: Codable, Identifiable, Hashable {
    var id: Int { level }
    let level: Int
    let title: String?
    let text: String
    /// Level 3 may carry the match it is about, so the card can draw both
    /// crests and the kickoff instead of a picture we do not have.
    let fixture: InfoFixture?

    var isToImpress: Bool { level >= 3 }
}

struct InfoFixture: Codable, Hashable {
    let home: String
    let away: String
    let homeApiId: Int?
    let awayApiId: Int?
    let kickoff: Date?
    let competition: String?

    enum CodingKeys: String, CodingKey {
        case home, away, kickoff, competition
        case homeApiId = "home_api_id"
        case awayApiId = "away_api_id"
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        home = try c.decode(String.self, forKey: .home)
        away = try c.decode(String.self, forKey: .away)
        homeApiId = try? c.decodeIfPresent(Int.self, forKey: .homeApiId)
        awayApiId = try? c.decodeIfPresent(Int.self, forKey: .awayApiId)
        competition = try? c.decodeIfPresent(String.self, forKey: .competition)
        // The routine writes ISO 8601 with or without fractional seconds; the
        // item decoder's date strategy is not applied inside nested strings
        // decoded here, so parse by hand and tolerate a bad value.
        if let raw = try? c.decodeIfPresent(String.self, forKey: .kickoff) {
            let f1 = ISO8601DateFormatter(); f1.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
            let f2 = ISO8601DateFormatter(); f2.formatOptions = [.withInternetDateTime]
            kickoff = f1.date(from: raw) ?? f2.date(from: raw)
        } else {
            kickoff = try? c.decodeIfPresent(Date.self, forKey: .kickoff)
        }
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(home, forKey: .home)
        try c.encode(away, forKey: .away)
        try c.encodeIfPresent(homeApiId, forKey: .homeApiId)
        try c.encodeIfPresent(awayApiId, forKey: .awayApiId)
        try c.encodeIfPresent(competition, forKey: .competition)
        if let kickoff {
            let f = ISO8601DateFormatter(); f.formatOptions = [.withInternetDateTime]
            try c.encode(f.string(from: kickoff), forKey: .kickoff)
        }
    }

    /// Crest URLs follow the same CDN shape as `Team.crestURL`.
    var homeCrestURL: URL? { homeApiId.flatMap { URL(string: "https://media.api-sports.io/football/teams/\($0).png") } }
    var awayCrestURL: URL? { awayApiId.flatMap { URL(string: "https://media.api-sports.io/football/teams/\($0).png") } }
}

/// Element-level lossy wrapper: a card that fails to decode becomes nil
/// instead of failing the whole array.
private struct LossyInfoCard: Decodable {
    let card: InfoCard?
    init(from decoder: Decoder) throws {
        card = try? InfoCard(from: decoder)
    }
}

// MARK: - Hashable conformance (id-based)
//
// SwiftUI's NavigationStack requires destination values to be Hashable. Two
// items with the same id are considered the same content; comparing other
// fields would cause spurious "different" results when the same item is
// loaded twice from different sources (cache vs API).
extension ContentItem: Hashable {
    static func == (lhs: ContentItem, rhs: ContentItem) -> Bool { lhs.id == rhs.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

