struct NextFixtureCard: Codable {
    let updatedAt: String?
    let opponent: String
    let date: String
    let venue: String
    let preview: String
    let talkingPoint: String?
    /// "League Cup (Carabao Cup), last 32" — written by team-page-generator
    /// from the fixture's own league (2026-09-08). Nil for a Premier League
    /// game, where naming the competition tells the reader nothing, and on
    /// rows written before the cups were covered.
    let competition: String?
    let leagueId: Int?
    let round: String?
    /// Deterministic pre-game verdict from FIFA ranks (B2). nil when either
    /// side's strength_rank is unknown — render nothing in that case.
    let favorite: FavoriteVerdict?

    enum CodingKeys: String, CodingKey {
        case updatedAt = "updated_at"
        case opponent
        case date
        case venue
        case preview
        case talkingPoint = "talking_point"
        case favorite
        case competition
        case leagueId = "league_id"
        case round
    }

    /// The competition without the sponsor parenthetical, for the narrow chip
    /// on the collapsed card: "League Cup (Carabao Cup), last 32" is a sentence
    /// and truncated to "League Cup (Caraba…" in a chip. The full prose form
    /// still reads in the expanded card's preview line.
    var competitionShort: String? {
        guard let competition, !competition.isEmpty else { return nil }
        let stripped = competition.replacingOccurrences(
            of: " *\\([^)]*\\)", with: "", options: .regularExpression)
        return stripped.isEmpty ? nil : stripped
    }
}

/// Pre-game favorite verdict carried on the Coming-up card payload.
struct FavoriteVerdict: Codable {
    let tag: String    // "likely_win" | "even" | "likely_loss"
    let label: String  // "Likely win" | "Could go either way" | "Likely loss"
}

/// One recent FINISHED fixture with the score, from this team's perspective.
/// Powers the collapsible "last games" section (E1).
struct RecentResult: Codable, Identifiable {
    var id: String { "\(date)-\(opponent)" }
    let date: String
    let opponent: String
    let venue: String        // "home" | "away"
    let teamScore: Int
    let oppScore: Int

    enum CodingKeys: String, CodingKey {
        case date, opponent, venue
        case teamScore = "team_score"
        case oppScore = "opp_score"
    }

    /// W / D / L from this team's perspective.
    var outcome: String {
        if teamScore > oppScore { return "W" }
        if teamScore < oppScore { return "L" }
        return "D"
    }
}

// MARK: - Team Page — Calendar tab (upcoming fixtures with importance)

/// One upcoming fixture with a server-generated importance rating.
/// Powers the Calendar tab on TeamPageView. The importance dots + label
/// come from team-page-generator's Claude pass using standings + form
/// context — derbies and direct top-4 / relegation collisions go 4-5,
/// mid-table league games go 2-3, friendlies / dead-rubbers go 1.
struct UpcomingFixture: Codable, Identifiable, Equatable {
    var id: String { "\(date)-\(opponent)" }
    let date: String                  // ISO 8601 kickoff datetime
    let opponent: String
    let venue: String                 // "home" | "away"
    let importanceDots: Int           // 1-5
    let importanceLabel: String       // ≤30 chars, statement form
    /// Opponent's API-Football id, for the crest. Nil on rows written
    /// before team-page-generator started emitting it (2026-09-07); the
    /// view then tries to resolve a PL club by name and otherwise shows
    /// the shield fallback.
    let opponentApiId: Int?

    enum CodingKeys: String, CodingKey {
        case date, opponent, venue
        case importanceDots = "importance_dots"
        case importanceLabel = "importance_label"
        case opponentApiId = "opponent_api_id"
    }

    var opponentCrestURL: URL? {
        if let id = opponentApiId { return URL(string: "https://media.api-sports.io/football/teams/\(id).png") }
        return Team.allCases.first {
            $0.displayName.caseInsensitiveCompare(opponent) == .orderedSame
                || $0.shortName.caseInsensitiveCompare(opponent) == .orderedSame
        }?.crestURL
    }
}

// MARK: - Team Page — Table tab (standings)

/// One row of standings. Used by both PL (20-row league table) and WC
/// (4-row group table). Populated by team-page-generator's mechanical
/// post-Claude merge from api_football_standings raw_fetch_log — no LLM
/// judgment, purely deterministic table data.
struct StandingsEntry: Codable, Identifiable, Equatable {
    /// Stable id for SwiftUI. Prefer the API-Football team id (unique
    /// across the league/group); fall back to rank for legacy rows that
    /// lack the id. Don't use plain `rank` alone — would collide if we
    /// ever render multiple groups in a single ForEach.
    var id: Int { teamIdApiFootball ?? rank }
    let rank: Int
    let teamName: String
    let teamIdApiFootball: Int?
    let played: Int
    let won: Int
    let drawn: Int
    let lost: Int
    let gf: Int
    let ga: Int
    let gd: Int
    let points: Int

